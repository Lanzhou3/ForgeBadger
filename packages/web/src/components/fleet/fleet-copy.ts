export type FleetCopy = Copy;

export function useFleetCopy(): FleetCopy {
  const { language } = useLanguage();
  return language === "en" ? en : language === "zh-TW" ? zhTW : zh;
}

/** Who acts next, in one sentence. Owner holds read as a question to the owner, everything else follows the flow model. */
export function taskSentence(copy: FleetCopy, task: FleetTask, flow: TaskFlow): { text: string; holder: TaskFlow["holder"] } {
  if (task.hold && task.status !== "cancelled" && task.status !== "passes") return { text: copy.sentence.holdAsk ?? "", holder: "owner" };
  if (flow.headline === "writing") return { text: copy.sentenceWriting(flow.actor ?? copy.workerFlagship), holder: flow.holder };
  if (flow.headline === "reviewing") return { text: copy.sentenceReviewing(flow.actor ?? "", flow.reviewRound ?? 1), holder: flow.holder };
  return { text: copy.sentence[flow.headline] ?? flow.headline, holder: flow.holder };
}
